function buildTranslations(entries: Record<string, TranslationEntry>): Record<LanguageCode, TranslationDictionary> {
  const result: Record<LanguageCode, TranslationDictionary> = {
    fr: {},
    en: {}
  };

  const languages: LanguageCode[] = ['fr', 'en'];
  const fallbackOrder: Record<LanguageCode, LanguageCode[]> = {
    fr: ['fr', 'en'],
    en: ['en', 'fr']
  };

  for (const [key, values] of Object.entries(entries)) {
    for (const language of languages) {
      const translation = fallbackOrder[language]
        .map((code) => values[code])
        .find((value) => typeof value !== 'undefined');

      if (typeof translation !== 'undefined') {
        result[language][key] = translation;
      }
    }
  }

  return result;
}

